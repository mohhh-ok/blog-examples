def get_api_key() -> str:
    key = os.environ.get("FISH_AUDIO_API_KEY", "")
    if not key:
        print("error: FISH_AUDIO_API_KEY is not set", file=sys.stderr)
        sys.exit(2)
    # 非秘匿診断: 長さと prefix のみ
    print(f"[key] length={len(key)} prefix={key[:4]}...", flush=True)
    return key
