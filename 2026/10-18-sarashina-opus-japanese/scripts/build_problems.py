def law_sentences(name, first_paragraph_only=False):
    t = (SRC / f"{name}.xml").read_text()
    if first_paragraph_only:
        t = t.split('<Paragraph Num="2"')[0]
    parts = re.findall(r"<(ItemTitle|Sentence)[^>]*>(.*?)</(?:ItemTitle|Sentence)>", t)
    lines, buf = [], ""
    for tag, s in parts:
        if tag == "ItemTitle":
            if buf:
                lines.append(buf)
            buf = s + "　"
        else:
            buf += s
    lines.append(buf)
    return "\n".join(lines)


def judgment_sentence(pdf_txt, start, n_sentences=1):
    t = (SRC / pdf_txt).read_text().replace("\n", "")
    t = re.sub(r"- \d+ -", "", t)
    i = t.index(start)
    out, j = "", i
    for _ in range(n_sentences):
        k = t.index("。", j) + 1
        # 「。）」のように括弧が続く場合は括弧まで含める
        while k < len(t) and t[k] in "）」":
            k += 1
        out, j = t[i:k], k
    return out


